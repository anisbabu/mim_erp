UPDATE product p
SET name_bn = t.bn
FROM (
    SELECT p2.id,
           translate(
               string_agg(
                   CASE
                       WHEN m.tok ~ '^[A-Za-z]+$' THEN coalesce(
                           (SELECT w.bn FROM bn_word w WHERE w.en = upper(m.tok)),
                           (SELECT string_agg(l.bn, '' ORDER BY c.i)
                              FROM regexp_split_to_table(upper(m.tok), '') WITH ORDINALITY c(ch, i)
                              JOIN bn_letter l ON l.en = c.ch))
                       ELSE m.tok
                   END, '' ORDER BY m.ord),
               '0123456789', '০১২৩৪৫৬৭৮৯') AS bn
    FROM product p2
    CROSS JOIN LATERAL (
        SELECT r.mt[1] AS tok, r.ord
        FROM regexp_matches(p2.name, '[A-Za-z]+|[^A-Za-z]+', 'g') WITH ORDINALITY r(mt, ord)
    ) m
    WHERE coalesce(trim(p2.name_bn), '') = ''
    GROUP BY p2.id
) t
WHERE p.id = t.id;
